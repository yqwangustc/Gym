"""Submit a single-node container job after successful external API preflight."""

import argparse
import asyncio
import shlex
import subprocess
from pathlib import Path

from omegaconf import OmegaConf

from environment_servers.audiomc_sim.slurm.config import TaskSettings, load_settings
from environment_servers.audiomc_sim.slurm.preflight import require_preflight


def sbatch_command(settings: TaskSettings, path: Path) -> list[str]:
    """Translate task Slurm settings into explicit sbatch arguments."""
    slurm = settings.slurm
    command = [
        "sbatch",
        "--nodes=1",
        "--ntasks=1",
        f"--job-name={slurm.job_name}",
        f"--time={slurm.time}",
        f"--gpus-per-node={slurm.gpus}",
        f"--cpus-per-task={slurm.cpus_per_task}",
        f"--chdir={settings.repos.nemo_gym}",
        f"--output={settings.output}/slurm-%j.log",
    ]
    if slurm.partition:
        command.append(f"--partition={slurm.partition}")
    if slurm.account:
        command.append(f"--account={slurm.account}")
    if slurm.exclusive:
        command.append("--exclusive")
    command.append(str(path.resolve()))
    return command


def srun_command(settings: TaskSettings, path: Path) -> list[str]:
    """Run service startup and collection together inside the allocated container."""
    mounts = list(settings.slurm.container_mounts)
    # Preserve configured absolute paths in the container, including resume artifacts.
    required = [
        settings.repos.nemo_gym,
        path.resolve().parent,
        settings.output,
        settings.backend.parent,
        *(p.parent for p in settings.mc_resources.model_dump().values()),
    ]
    if settings.environment:
        required.append(settings.environment.parent)
    for directory in required:
        mount = f"{directory}:{directory}"
        if mount not in mounts:
            mounts.append(mount)
    return [
        "srun",
        "--nodes=1",
        "--ntasks=1",
        "--cpu-bind=none",
        "--gpu-bind=none",
        "--kill-on-bad-exit=1",
        f"--container-image={settings.container}",
        f"--container-mounts={','.join(mounts)}",
        f"--container-workdir={settings.repos.nemo_gym}",
        settings.slurm.python,
        "-m",
        "environment_servers.audiomc_sim.slurm.incontainer_run",
        "--settings",
        str(path.resolve()),
    ]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--settings", type=Path, required=True)
    args = parser.parse_args()
    settings = load_settings(args.settings)
    settings.output.mkdir(parents=True, exist_ok=True)
    asyncio.run(require_preflight(settings))
    # Resolve host paths before submission; the batch job needs only bash and srun.
    launch_settings = settings.output / "launch_settings.yaml"
    OmegaConf.save(OmegaConf.create(settings.model_dump(mode="json")), launch_settings)
    script = settings.output / "run.sbatch"
    script.write_text(
        "#!/usr/bin/env bash\n"
        "# SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.\n"
        "# SPDX-License-Identifier: Apache-2.0\n"
        "# Generated by slurm.submit from task settings.\n"
        "set -euo pipefail\n"
        "exec " + shlex.join(srun_command(settings, launch_settings)) + "\n"
    )
    subprocess.run(sbatch_command(settings, script), check=True, cwd=settings.repos.nemo_gym)


if __name__ == "__main__":
    main()
